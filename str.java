public class str {
    public static void main(String[] args) {
        String str = "Hello, ";
        String strr = "Rohith!";
        System.out.println("This is length method, can be used by var_name.length(): " + str.length());
        System.out.println("This is replace method, can be used by var_name.replace(): " + str.replace("Hello", "Java"));
        System.out.println("This is compare method, can be used by var_name.compare(): " + str.compareTo(strr));
        System.out.println("This is concatenate method, can be used by var_name.concat(var1_name or str): " + str.concat(strr));
        System.out.println("This is toUpperCase method, can be used by var_name.toUpperCase(): " + strr.toUpperCase());
        System.out.println("This is toLowerCase method, can be used by var_name.toLowerCase(): " + strr.toLowerCase());
    }
}
